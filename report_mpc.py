def check_readme_numbers(readme_text, S, R0):
    """Rule P4: the Part 2 section of README.md must equal the one generated from the result files.
    Returns a list of differing lines (empty = OK)."""
    m = re.search(re.escape(README_START) + r".*?" + re.escape(README_END), readme_text, re.S)
    if not m:
        return ["Part 2 section not found"]
    have, want = m.group(0).replace("\r\n", "\n").split("\n"), readme_section(S, R0).split("\n")
    diff = [f"line {i}: README '{a}' / generated '{b}'" for i, (a, b) in enumerate(zip(have, want)) if a != b]
    if len(have) != len(want):
        diff.append(f"length {len(have)} / {len(want)} lines")
    return diff


def write_readme(S, R0):
    text = README.read_text(encoding="utf-8")
    sec = readme_section(S, R0)
    pat = re.compile(re.escape(README_START) + r".*?" + re.escape(README_END), re.S)
    if pat.search(text):
        text = pat.sub(lambda _: sec, text)
    else:
        anchor = "**Background.**"
        text = text.replace(anchor, sec + "\n\n" + anchor, 1) if anchor in text else text + "\n" + sec + "\n"
    README.write_text(text, encoding="utf-8")


