def md_table(head, rows):
    """Markdown table; a "|" inside a cell (e.g. |dTc|) is escaped, otherwise it splits the cell when rendered."""
    esc = lambda x: str(x).replace("|", "\\|")   # noqa: E731
    return "\n".join(["| " + " | ".join(esc(h) for h in head) + " |", "|" + "---|" * len(head)]
                     + ["| " + " | ".join(esc(x) for x in r) + " |" for r in rows])


def scenario_table(S, scen):
    head = ["Configuration", "IAE, mol/L min", "worst seed", "TV of Tc, K", "highest T, K", "ignitions",
            "supervisor not normal"]
    rows = []
    for c in configs(S, scen):
        sd, iae = values(S, scen, c, IAE)
        _, tv = values(S, scen, c, TV)
        _, mt = values(S, scen, c, MAXT)
        ign = sum(int(m["ignition"]) for _, m in runs(S, scen, c))
        _, sup = values(S, scen, c, lambda m: m["share_not_normal"])
        rows.append([c, spread(iae), worst(sd, iae), spread(tv, 1), worst(sd, mt, 1), f"{ign} of {len(sd)}",
                     spread(100 * sup, 1) + " %" if rm.CONFIGS[c][2] else "-"])
    return md_table(head, rows)


