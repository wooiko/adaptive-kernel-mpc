def load_step_time():
    return json.loads(STEP_FILE.read_text()) if STEP_FILE.exists() else None


def step_check(ST):
    """D15 (refined 13.10.2026): per K-MPC configuration the median over valid passes of A (CPU p95 of all samples in the
    set together) <= STEP_LIMIT_MS. Returns (passed, highest median A, its configuration) or None if not measured."""
    if not ST or not ST.get("complete") or not ST.get("decision"):
        return None
    dec = {c: d for c, d in ST["decision"].items() if c.startswith("K-MPC")}
    w = max(dec, key=lambda c: dec[c]["A_median_ms"])
    return all(d["A_median_ms"] <= STEP_LIMIT_MS for d in dec.values()), dec[w]["A_median_ms"], w


def criteria(S, R0, ST=None):
    """ST: result of measure_step_time.py (None: read outputs/mpc_step_time.json)."""
    ST = load_step_time() if ST is None else ST
    """The checks of TZ section 9 that the result files decide. Returns a list of dicts."""
    out = []
    viol = sum(m["violations"] for sc in SCENARIOS for c in configs(S, sc) for _, m in runs(S, sc, c))
    viol0 = sum(m["violations"] for sc in R0["results"].values() for m in sc.values())
    n_runs = sum(len(runs(S, sc, c)) for sc in SCENARIOS for c in configs(S, sc))
    out.append({"id": "violations", "text": "Violations of the hard input constraints, all runs of all controllers",
                "value": f"{viol} in {n_runs} runs over {len(seeds(S))} seeds; {viol0} in the runs of "
                         f"outputs/mpc_metrics.json (seed 0, oracle included)", "pass": viol == 0 and viol0 == 0})
    ign = {c: sum(int(m["ignition"]) for sc in IN_SET for _, m in runs(S, sc, c)) for c in KMPC_CRIT}
    tmax = max(m["max_T"] for c in KMPC_CRIT for sc in IN_SET for _, m in runs(S, sc, c))
    out.append({"id": "ignition", "text": f"Ignition (T > {cl.IGNITION_T:.0f} K) in {', '.join(IN_SET)}, "
                                         f"{' and '.join(KMPC_CRIT)}, all seeds",
                "value": "; ".join(f"{c}: {n} runs" for c, n in ign.items()) + f"; highest T {tmax:.1f} K",
                "pass": all(n == 0 for n in ign.values())})
    ss = {c: values(S, "S2", c, lambda m: m["ss_error_max_abs_hold"]) for c in KMPC_CRIT}
    out.append({"id": "s2", "text": f"S2: |steady-state error| on the true Ca <= {SS_LIMIT} mol/L, both K-MPC, every seed",
                "value": "; ".join(f"{c}: worst {worst(*ss[c])}" for c in KMPC_CRIT),
                "pass": all(np.all(ss[c][1] <= SS_LIMIT) for c in KMPC_CRIT)})
    fb = fallback_table(S)
    bad = [r for r in fb if r["share"] > FALLBACK_LIMIT]
    out.append({"id": "fallback", "text": f"Fallback plan in at most {100 * FALLBACK_LIMIT:.1f} % of the steps of each MPC "
                                         f"configuration, all seeds of {', '.join(IN_SET)} together (TZ 14, D11)",
                "value": "highest " + max(fb, key=lambda r: r["share"])["text"], "pass": not bad})
    sc = step_check(ST)
    out.append({"id": "step_time", "text": f"K-MPC step time: CPU time of identifier + controller per sample, 95th percentile "
                                          f"of all samples of each configuration in {', '.join(IN_SET)}, median of the "
                                          f"valid passes <= {STEP_LIMIT_MS:.0f} ms, one process on one vCPU, one BLAS "
                                          "thread (TZ 14, D15 refined 13.10.2026)",
                "value": ("not measured (outputs/mpc_step_time.json missing or incomplete)" if sc is None else
                          f"highest {sc[1]:.1f} ms ({sc[2]})"),
                "pass": bool(sc and sc[0])})
    return out


def fallback_table(S):
    rows = []
    for conf in rm.CONFIGS:
        if not is_mpc(conf) or conf == "NMPC on the true model (oracle)":
            continue
        n = s = 0
        for sc in IN_SET:
            for _, m in runs(S, sc, conf):
                n += m["fallback_steps"]; s += m["n_steps"]
        if s:
            rows.append({"conf": conf, "fallback": n, "steps": s, "share": n / s,
                         "text": f"{n} of {s} steps ({100 * n / s:.3f} %, {conf})"})
    return rows


def fallback_cases(S, R0):
    """Every run with a fallback step, S5b included, plus the oracle runs of seed 0."""
    cases = []
    for sc in SCENARIOS:
        for c in configs(S, sc):
            for s, m in runs(S, sc, c):
                if m["fallback_steps"]:
                    cases.append((sc, c, s, m["fallback_steps"], m["n_steps"],
                                  {k: v for k, v in m["statuses"].items() if k != "solved"}))
    for sc, rr in R0["results"].items():
        m = rr.get("NMPC on the true model (oracle)")
        if m and m["fallback_steps"]:
            cases.append((sc, "NMPC on the true model (oracle)", R0["seed"], m["fallback_steps"], m["n_steps"],
                          {k: v for k, v in m["statuses"].items() if k != "solved"}))
    return cases


def step_table(S, scens=SCENARIOS, key="full_ms"):
    """Time per sample over the runs of each configuration in `scens`. key: "full_ms" (identifier + controller, the
    step of TZ 4 by D15), "step_ms" (controller only: QP and its preparation) or "ident_ms" (identifier only)."""
    rows = []
    for conf in rm.CONFIGS:
        allr = [(sc, s, m) for sc in scens for s, m in runs(S, sc, conf)]
        if not allr:
            continue
        sc_w, s_w, m_w = max(allr, key=lambda t: t[2][key]["p95"])
        rows.append({"conf": conf, "median": float(np.median([m[key]["median"] for *_, m in allr])),
                     "p95_med": float(np.median([m[key]["p95"] for *_, m in allr])),
                     "p95_max": m_w[key]["p95"], "where": f"{sc_w}, seed {s_w}",
                     "max": max(m[key]["max"] for *_, m in allr), "runs": len(allr)})
    return rows


def ties(A, B, tol=TIE_TOL):
    """Equal within the relative tolerance TIE_TOL (audit 1, C3: differences of the solver's numerical noise)."""
    A, B = np.asarray(A, float), np.asarray(B, float)
    return np.abs(A - B) <= tol * np.maximum(np.abs(A), np.abs(B))


def pair_stats(S, a, b, scen, key=IAE):
    sa, va = values(S, scen, a, key)
    sb, vb = values(S, scen, b, key)
    common = sorted(set(sa) & set(sb))
    if not common:
        return None
    A = np.array([va[list(sa).index(s)] for s in common])
    B = np.array([vb[list(sb).index(s)] for s in common])
    eq = ties(A, B)
    return {"n": len(common), "a_better": int(np.sum((A < B) & ~eq)), "ties": int(np.sum(eq)),
            "ratio_median": float(np.median(A / B))}


